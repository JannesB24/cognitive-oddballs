from __future__ import annotations
import numpy as np
from typing import Dict, Callable, Tuple, List
from ..models.base import BaseModel
from ..data.utils import get_observations
from ..inference.mle import grid_search_mle, bic
from ..inference.laplace import map_via_grid, laplace_evidence

def recover_one_environment(
    models: Dict[str, Callable[..., BaseModel]],
    true_params: Dict[str, np.ndarray],
    grids: Dict[str, np.ndarray],
    env_fn: Callable[..., Any],
    n_trials: int,
    sigma_r: float,
    decision_rule: str = "BIC",
) -> Dict[str, Dict[str, Dict[str, any]]]:
    """
    Run a **single** simulated dataset generated by each true model,
    fit *all* candidate models and store the results.
    Returns a nested dict `results[true_model][fit_model][...]`.
    """
    results: Dict[str, Dict[str, Dict[str, any]]] = {}

    # --------------------------------------------------------------
    # 1. generate the data once per true model
    # --------------------------------------------------------------
    for true_name, true_cls in models.items():
        # generate stimuli
        env_out = env_fn(n_trials=n_trials, seed=42)
        observations = get_observations(env_out)

        # instantiate the *generating* model
        true_mod = true_cls(*true_params[true_name])
        beliefs, responses, _ = run_on_sequence(
            true_mod, observations, sigma_r, generate_responses=True
        )
        # responses are the behavioural data that the fitting models will see
        results[true_name] = {}

        # --------------------------------------------------------------
        # 2️. fit every candidate model
        # --------------------------------------------------------------
        for fit_name, fit_cls in models.items():
            # ---- MLE + BIC ----
            best_params, best_ll = grid_search_mle(
                fit_cls, grids[fit_name], observations, responses, sigma_r
            )
            k = fit_cls(*best_params).n_params      # or use a helper function
            bic_val = bic(k, n_trials, best_ll)

            # ---- MAP + Laplace ----
            map_params, logpost = map_via_grid(
                fit_cls, grids[fit_name], observations, responses, sigma_r
            )
            log_evidence = laplace_evidence(
                fit_cls, map_params, logpost, observations, responses, sigma_r
            )

            results[true_name][fit_name] = {
                "MLE": {"best_params": best_params, "loglik": best_ll, "BIC": bic_val},
                "Bayesian": {"MAP": map_params, "log_evidence": log_evidence},
            }

    return results